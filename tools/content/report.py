def raw_totals(iid, qty=1.0, acc=None, depth=0):
    acc = acc if acc is not None else defaultdict(float)
    rid = C.chosen_recipe.get(iid)
    if rid is None or depth > 40:
        acc[iid] += qty
        return acc
    ins, outs = net_io(C.recipes[rid])
    crafts = qty / outs[iid]
    for i, a in ins.items():
        raw_totals(i, a * crafts, acc, depth + 1)
    return acc


def fmt_io(d):
    return " + ".join(f"{C.items[k]['name']} ×{v:g}" for k, v in d.items())


def recipe_line(rid):
    r = C.recipes[rid]
    return f"{fmt_io(r['inputs'])} → {fmt_io(r['outputs'])} *({r['category']}, {r['time']:g} s)*"


def render():
    items, recipes, blds, techs = C.items, C.recipes, C.buildings, C.techs
    out = ["# Content stats", "",
           "_Auto-generated by `tools/content/build_content.py` — do not edit by hand._", ""]
    counts = scale_counts()
    out += ["## Totals", "", "| content | count | minimum |", "|---|---:|---:|"]
    for k, v in counts.items():
        out.append(f"| {k} | {v} | {MINIMUMS.get(k, '')} |")

    out += ["", "## Items by group and tier", ""]
    tiers = list(range(8))
    out.append("| group | " + " | ".join(f"T{t}" for t in tiers) + " | total |")
    out.append("|---|" + "---:|" * (len(tiers) + 1))
    grid = Counter((i["group"], i["tier"]) for i in items.values())
    for g in GROUPS:
        row = [grid[(g, t)] for t in tiers]
        if sum(row):
            out.append(f"| {g} | " + " | ".join(str(x or "") for x in row) + f" | {sum(row)} |")
    tier_tot = Counter(i["tier"] for i in items.values())
    out.append("| **all** | " + " | ".join(str(tier_tot[t]) for t in tiers) + f" | {len(items)} |")

    out += ["", "## Raw resources", "", "| resource | kind | tier | base value ¢ | deposit |", "|---|---|---:|---:|---|"]
    for iid in sorted(C.base_values, key=lambda i: (items[i]["tier"], i)):
        it = items[iid]
        out.append(f"| {it['name']} | {it['kind']} | {it['tier']} | {it['value']:g} | {C.deposits[iid]['name']} |")

    out += ["", "## Recipes by category", "", "| category | recipes | buildings (speed) |", "|---|---:|---|"]
    cat_count = Counter(r["category"] for r in recipes.values())
    for c in CATEGORIES:
        runners = sorted((b for b in blds.values() if c in b["categories"]), key=lambda b: b["tier"])
        out.append(f"| {c} | {cat_count[c]} | " + ", ".join(f"{b['name']} ({b['speed']:g})" for b in runners) + " |")

    out += ["", "## Buildings by role and tier", ""]
    out.append("| role | " + " | ".join(f"T{t}" for t in tiers) + " | total |")
    out.append("|---|" + "---:|" * (len(tiers) + 1))
    bgrid = Counter((b["role"], b["tier"]) for b in blds.values())
    for role in sorted({b["role"] for b in blds.values()}):
        row = [bgrid[(role, t)] for t in tiers]
        out.append(f"| {role} | " + " | ".join(str(x or "") for x in row) + f" | {sum(row)} |")

    out += ["", "## Techs by tier and branch", ""]
    branches = sorted({t["branch"] for t in techs.values()})
    out.append("| branch | " + " | ".join(f"T{t}" for t in tiers) + " | total |")
    out.append("|---|" + "---:|" * (len(tiers) + 1))
    tgrid = Counter((t["branch"], t["tier"]) for t in techs.values())
    for br in branches:
        row = [tgrid[(br, t)] for t in tiers]
        out.append(f"| {br} | " + " | ".join(str(x or "") for x in row) + f" | {sum(row)} |")
    ttot = Counter(t["tier"] for t in techs.values())
    out.append("| **all** | " + " | ".join(str(ttot[t]) for t in tiers) + f" | {len(techs)} |")
    leveled = sum(1 for t in techs.values() if t["effects"] and not t["unlocks"] and not t["repeatable"])
    out.append("")
    out.append(f"Unlock techs: {sum(1 for t in techs.values() if t['unlocks'])} · leveled bonus techs: {leveled} · "
               f"repeatable: {sum(1 for t in techs.values() if t['repeatable'])}")
    out.append("")
    out.append("Typical total research per tier (median units × cost items):")
    out.append("")
    for t in tiers:
        rows = sorted(x["units"] for x in techs.values() if x["tier"] == t and not x["repeatable"])
        if rows:
            ex = next(x for x in techs.values() if x["tier"] == t)
            cost = ", ".join(f"{items[k]['name']} ×{v}" for k, v in ex["cost"].items())
            out.append(f"- T{t}: {rows[0]}–{rows[-1]} units (median {rows[len(rows) // 2]}), per unit {cost}")

    out += ["", "## World", ""]
    out.append(f"{len(C.deposits)} deposits · {len(C.sectors)} sectors · {len(C.threats)} threats · "
               f"{len(C.contracts)} contracts · {len(C.achievements)} achievements · {len(C.megaprojects)} megaprojects")
    out += ["", "| # | sector | tier | defense req. | base threat | deposits (slots) |", "|---:|---|---:|---:|---:|---|"]
    for s in sorted(C.sectors.values(), key=lambda s: s["order"]):
        deps = ", ".join(f"{C.deposits[d]['name']} {n}" for d, n in s["deposits"].items())
        out.append(f"| {s['order']} | {s['name']} | {s['tier']} | {s['defense_required']} | {s['threat']} | {deps} |")
    out += ["", "| threat | kind | strength | appears at pollution |", "|---|---|---:|---:|"]
    for t in C.threats.values():
        out.append(f"| {t['name']} | {t['kind']} | {t['strength']} | {t['appears_at_pollution']} |")
    out += ["", "Megaprojects:", ""]
    for mp in C.megaprojects.values():
        out.append(f"- **{mp['name']}** (T{mp['tier']}, {len(mp['stages'])} stages): "
                   + "; ".join(st["name"] for st in mp["stages"]))

    out += ["", "## Power balance (speed 1.0)", "",
            "- Burner Boiler: 2400 kW of fuel → 40 steam/s → **2 Steam Engines** (20 steam/s, 900 kW each).",
            "- High-Pressure Boiler (speed 2.5): 6000 kW → 100 steam/s → **5 Steam Engines**.",
            "- Fired Superheater: 2400 kW, 40 steam → 40 superheated steam/s → **1 Steam Turbine** (4000 kW).",
            "- Thorium Reactor: 1 fuel rod / 25 s → 160 superheated steam/s → **4 Steam Turbines** (16 MW).",
            "- Breeder Reactor (speed 2, breeding cycle): 240 superheated/s → **6 Steam Turbines**; breeds 1 seed per rod.",
            "- Tokamak: 1 pellet / 25 s → 600 superheated steam/s → **15 Steam Turbines** (60 MW) for 6 MW of magnets.",
            "- Gas Turbine: 10 fuel gas/s → 3 MW. Combined-Cycle Turbine: 20 fuel gas/s → 9 MW.",
            "- Solar 90 kW / Thin-Film 400 kW peak (day/night); Wind 300 kW / Heavy Wind 1.8 MW; Tidal 1.5 MW; Geothermal 6 MW.",
            "- Accumulators: Flywheel 20 MJ, Battery Bank 100 MJ, Lithium Array 800 MJ, SMES Ring 5 GJ."]

    out += ["", "## Main production chains", ""]
    for title, iid, blurb in CHAINS:
        it = items[iid]
        out.append(f"### {title}: {it['name']} (T{it['tier']}, {it['value']:g}¢)")
        out.append("")
        out.append(blurb)
        out.append("")
        rid = C.chosen_recipe.get(iid)
        if rid:
            out.append(f"- {recipe_line(rid)}")
            for inp in recipes[rid]["inputs"]:
                sub = C.chosen_recipe.get(inp)
                if sub and sub != rid:
                    out.append(f"  - {recipe_line(sub)}")
        raws = raw_totals(iid)
        out.append("")
        out.append("Raw per unit: " + ", ".join(f"{items[k]['name']} {sig3(v):g}" for k, v in
                                                 sorted(raws.items(), key=lambda kv: -kv[1] * items[kv[0]]['value'])))
        out.append("")

    out += ["## Research item costs", "", "| research item | tier | value ¢ | raw resources per unit |", "|---|---:|---:|---|"]
    for iid in ["blueprint_sheet", "circuit_schematic", "field_report", "chemical_assay", "alloy_specimen",
                "flight_telemetry", "quantum_datacore"]:
        it = items[iid]
        raws = raw_totals(iid)
        out.append(f"| {it['name']} | {it['tier']} | {it['value']:g} | " +
                   ", ".join(f"{items[k]['name']} {sig3(v):g}" for k, v in sorted(raws.items(), key=lambda kv: -kv[1])) + " |")
    out.append("")
    return "\n".join(out)


def print_summary():
    counts = scale_counts()
    print("INDUSTRIUM content build OK")
    for k, v in counts.items():
        print(f"  {k:<20} {v:>5}   (min {MINIMUMS[k]})")
    vals = sorted((i["value"], i["id"]) for i in C.items.values())
    print(f"  value range         {vals[0][0]:g}¢ ({vals[0][1]}) .. {vals[-1][0]:g}¢ ({vals[-1][1]})")
    by_tier = defaultdict(list)
    for i in C.items.values():
        if i["group"] not in ("raw", "production", "power", "logistics", "defense"):
            by_tier[i["tier"]].append(i["value"])
    print("  median value/tier   " + "  ".join(f"T{t}:{sorted(v)[len(v) // 2]:g}" for t, v in sorted(by_tier.items())))
    print(f"  warnings            {len(C.warnings)}")
    print("  wrote data/items.json, recipes.json, buildings.json, techs.json, world.json, docs/CONTENT_STATS.md")
